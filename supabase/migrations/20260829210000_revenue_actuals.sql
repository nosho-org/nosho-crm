-- ---------------------------------------------------------------------------
-- Chiffres lus sur le compte Qonto principal, en sommant les credits dont le
-- libelle est "Stichting Mollie Payments" -- l'entite qui reverse les
-- paiements collectes par Mollie.
--
-- Aout n'y figure pas, et c'est la regle : un mois en cours n'a pas de total.
insert into public.revenue_actuals (month, source, amount, transaction_count)
values
    ('2026-06-01', 'mollie', 3123.21, 5),
    ('2026-07-01', 'mollie', 3166.31, 8)
on conflict (month, source) do update
    set amount = excluded.amount,
        transaction_count = excluded.transaction_count,
        fetched_at = now();
